// ── Helper: Find medicine by any name ─────────────────────────────────────
export function findMedicine(name: string): MedicineInfo | null {
  if (!name) return null;
  const lowerName = name.toLowerCase().trim();

  // Direct key match
  if (MEDICINE_DATABASE[lowerName]) return MEDICINE_DATABASE[lowerName];

  // Search by brand or generic name
  for (const [, info] of Object.entries(MEDICINE_DATABASE)) {
    if (
      info.generic_name.toLowerCase().includes(lowerName) ||
      info.brand_names.some(b => b.toLowerCase().includes(lowerName) || lowerName.includes(b.toLowerCase()))
    ) {
      return info;
    }
  }
  return null;
}

