function calculateEndDate(durationStr: string): string {
  const match = durationStr.match(/(\d+)\s*day/i);
  const days = match ? parseInt(match[1]) : 5;
  const end = new Date();
  end.setDate(end.getDate() + days);
  return end.toISOString().split('T')[0];
}
